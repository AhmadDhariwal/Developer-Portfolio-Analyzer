// Keep one editable page theme, emitting only selectors used by each emulated view.
// Run after changing either theme or its page/child templates, then format outputs.
const fs = require('node:fs');
const path = require('node:path');
const sass = require('sass');
const postcss = require('postcss');
const root = path.resolve(__dirname, '../src/app/pages');
for (const module of ['resume-analyzer']) {
  const directory = path.join(root, module);
  const theme = path.join(directory, 'styles', `_${module}-theme.scss`);
  const css = sass.compile(theme, { style: 'expanded', charset: false }).css;
  const files = [path.join(directory, `${module}.component.html`)];
  for (const child of fs.readdirSync(path.join(directory, 'components'))) {
    if (!fs.statSync(path.join(directory, 'components', child)).isDirectory()) continue;
    if (
      module === 'notifications' &&
      ['notification-bulk-actions', 'notification-confirm-dialog'].includes(child)
    )
      continue;
    files.push(path.join(directory, 'components', child, `${child}.component.html`));
  }
  for (const htmlFile of files) {
    const html = fs.readFileSync(htmlFile, 'utf8');
    const classes = new Set(
      [...html.matchAll(/class="([^"]+)"/g)].flatMap((match) => match[1].split(/\s+/)),
    );
    for (const match of html.matchAll(/\[class\.([\w-]+)\]/g)) classes.add(match[1]);
    // Dynamic pure presentation helpers return these three existing score classes.
    if (html.includes('getScoreClass('))
      ['score-high', 'score-mid', 'score-low'].forEach((name) => classes.add(name));
    if (html.includes('priority-badge--'))
      ['high', 'medium', 'low'].forEach((tone) => classes.add(`priority-badge--${tone}`));
    const tags = new Set([...html.matchAll(/<([a-z][\w-]*)/g)].map((match) => match[1]));
    const isParent = path.dirname(htmlFile) === directory;
    const tree = postcss.parse(css);
    tree.walkRules((rule) => {
      const selectors = rule.selectors.filter((selector) => {
        if (selector.trim() === ':host') return isParent;
        const local = selector.replace(/:host-context\([^)]*\)/g, '');
        const names = [...local.matchAll(/\.([a-zA-Z_][\w-]*)/g)].map((match) => match[1]);
        if (names.length) return names.every((name) => classes.has(name));
        const elements = [...local.matchAll(/(?:^|[\s>+~,(])([a-z][\w-]*)/g)].map(
          (match) => match[1],
        );
        return elements.every((tag) => tags.has(tag));
      });
      if (!selectors.length) rule.remove();
      else rule.selectors = selectors;
    });
    tree.walkAtRules((rule) => {
      if (rule.nodes?.length === 0) rule.remove();
    });
    const out = htmlFile.replace('.html', '.scss');
    fs.writeFileSync(
      out,
      `// Generated by scripts/prepare-resume-styles.cjs from styles/_${module}-theme.scss.\n${tree.toString()}\n${isParent ? '' : ':host { display: contents; }\n'}`,
    );
    if (!isParent) {
      const tsFile = htmlFile.replace('.html', '.ts');
      const stem = path.basename(out);
      const code = fs
        .readFileSync(tsFile, 'utf8')
        .replace(/styleUrls:\s*\[[^\]]+\],\s*styles:\s*\[[^\]]+\]/, `styleUrl: './${stem}'`);
      fs.writeFileSync(tsFile, code);
    }
  }
}
